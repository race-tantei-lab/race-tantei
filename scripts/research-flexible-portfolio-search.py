#!/usr/bin/env python3
"""Flexible, label-blind JRA portfolio policy search.

Unconstrained research dimensions: 0..12 races per venue-day, 1..64+ tickets
per race, one or multiple bet types/combinations, all nonempty subsets of
the six markets, 100..300,000 yen nominal race budget and dynamic scaling, multiple stake allocations,
probability/conditional-payout ranking styles and pre-result abstention.
Do not hardcode 5 races / 2 tickets / 1,900+100 / a single market combination.

Candidate values are generated by models fitted only on an earlier period;
the ONLY post-race field 'payout100' is accessed in settlement, never choice.

Choose parameters on 2025; apply the identical frozen parameters to 2026.
2026 was previously inspected by research: not independent prospective proof.
Archive runner T-15 provenance is unverified; not production-promotable.
"""
from __future__ import annotations
from collections import defaultdict, Counter
from dataclasses import asdict, dataclass
import hashlib
import itertools
import json
import math
import random
import sys
from typing import Any

MARKETS=("単勝","ワイド","馬連","馬単","3連複","3連単")
RANK_MODES=("expected","safer","longshot","hit","logvalue","convex")
RACE_COUNTS=tuple(range(13))  # zero means all signals above threshold
TICKET_COUNTS=tuple(range(1,65))
BET_BUDGETS=(100,300,500,1000,2000,5000,10000,20000,50000,100000,300000)
STAKES=("equal","score","score_squared","topheavy","probability")
MARKET_CAPS=(1,2,4,8,16,64)
EV_THRESHOLDS=(0.0,0.8,1.0,1.2,1.5,2.0)
RACE_BUDGET_MODES=("flat","proportional_ev","square_root_ev","stepwise_ev")
VENUES=("札幌","函館","福島","新潟","東京","中山","中京","京都","阪神","小倉")
RACE_FILTERS=("all","field_le10","field_gt10","early_1_6","late_7_12",
  "turf","dirt","sprint_lt1600","middle_1600_2000","stayer_gt2000")+tuple("venue:"+x for x in VENUES)
ANCHOR_TICKET_COUNTS=(1,2,3,4,6,8,12,16,24,32,48,64)
SEED=20261108

@dataclass(frozen=True)
class Policy:
    rank_mode:str
    market_mask:int
    max_per_type:int
    ticket_count:int
    budget:int
    stake_mode:str
    races_per_venue_day:int
    min_expected_ev:float
    race_budget_mode:str="flat"
    race_filter:str="all"

def market_allowed(mask:int,kind:str)->bool:
    return bool(mask & (1<<MARKETS.index(kind)))

def all_policies(limit:int=5000,seed:int=SEED)->list[Policy]:
    """Predeclare candidate hypotheses. Sampling never accesses return labels."""
    if limit<1:raise ValueError("POLICY_SEARCH_LIMIT_INVALID")
    rng=random.Random(seed)
    configs=set()
    def one():
        mode=rng.choice(RANK_MODES)
        mask=rng.randrange(1,1<<len(MARKETS))
        per=rng.choice(MARKET_CAPS)
        count=rng.choice(TICKET_COUNTS)
        b=rng.choice(BET_BUDGETS)
        if count>min(64,per*mask.bit_count()) or b<100*count:return None
        return Policy(mode,mask,per,count,b,rng.choice(STAKES),
                      rng.choice(RACE_COUNTS),rng.choice(EV_THRESHOLDS),
                      rng.choice(RACE_BUDGET_MODES),rng.choice(RACE_FILTERS))
    # Anchors guarantee interpretation of all counts, bankrolls, stake methods,
    # all six markets and long-shot abstention regardless of random sampling.
    anchor_cap=max(1,limit//5)  # leave >=80% for broad random hypotheses
    for count in ANCHOR_TICKET_COUNTS:
        for racecount in RACE_COUNTS:
            for stake in STAKES:
                for budget in BET_BUDGETS:
                    if budget>=100*count:
                        configs.add(Policy("expected",63,32,count,budget,
                                           stake,racecount,0.0))
                        if len(configs)>=anchor_cap:break
                if len(configs)>=limit:break
            if len(configs)>=limit:break
        if len(configs)>=limit:break
    tries=0
    while len(configs)<limit and tries<limit*200:
        v=one()
        if v is not None:configs.add(v)
        tries+=1
    return sorted(configs,key=lambda p:repr(p))[:limit]

def criterion(c:dict[str,Any],mode:str)->float:
    ev=float(c["riskAdjustedE"])
    ph=float(c["hitP"])
    if not (math.isfinite(ev) and math.isfinite(ph) and ev>=0 and 0<ph<=1):
        raise ValueError("INVALID_PRE_RACE_MODEL_ESTIMATE")
    if mode=="expected":return ev
    if mode=="safer":return ev*math.sqrt(ph)
    if mode=="longshot":return ev/math.sqrt(max(.01,ph))
    if mode=="hit":return ph
    if mode=="logvalue":return math.log1p(ev)*math.sqrt(ph)
    if mode=="convex":return ev*ev/math.sqrt(max(.01,ph))
    raise ValueError("UNRECOGNIZED_TICKET_RANK_MODE")

# Frozen candidate rankings are reused across thousands of stake/race-policy
# trials, avoiding re-sorting all horse combinations on every grid point.
# Hold the source list reference to detect stale/reused object IDs.
_RANK_CACHE:dict[tuple[int,str],tuple[list,list]]={}

def clear_rank_cache():
    _RANK_CACHE.clear()

def candidate_choices(tickets:list[dict[str,Any]],p:Policy):
    # No payout field read in candidate selection; the only settlement label
    # is deliberately accessed later AFTER tickets and stake are frozen.
    cache_key=(id(tickets),p.rank_mode)
    found=_RANK_CACHE.get(cache_key)
    if found is not None and found[0] is tickets:
        ranked=found[1]
    else:
        ranked=sorted((
          (criterion(t,p.rank_mode),str(t["key"][0]),tuple(t["key"][1]),t)
          for t in tickets
        ),key=lambda x:(-x[0],x[1],x[2]))
        _RANK_CACHE[cache_key]=(tickets,ranked)
    chosen=[];types=Counter()
    for val,kind,combo,ticket in ranked:
        if not market_allowed(p.market_mask,kind):continue
        if types[kind]>=p.max_per_type:continue
        chosen.append((val,ticket));types[kind]+=1
        if len(chosen)==p.ticket_count:break
    return chosen if len(chosen)==p.ticket_count else []

def allocate_stakes(chosen:list[tuple[float,dict[str,Any]]],p:Policy)->list[int]:
    """Deterministic ¥100 grid; full race budget conserved, no hidden cash."""
    n=len(chosen)
    if n!=p.ticket_count or n==0 or p.budget<100*n:raise ValueError("STAKE_POLICY_UNFUNDED")
    stake=[100]*n
    extra=(p.budget-100*n)//100
    if not extra:return stake
    scores=[max(1e-8,float(q[0])) for q in chosen]
    probs=[max(1e-8,float(q[1]["hitP"])) for q in chosen]
    if p.stake_mode=="equal":w=[1.0]*n
    elif p.stake_mode=="score":w=scores
    elif p.stake_mode=="score_squared":w=[x*x for x in scores]
    elif p.stake_mode=="topheavy":w=[20.0]+[1.0]*(n-1)
    elif p.stake_mode=="probability":w=probs
    else:raise ValueError("UNKNOWN_STAKE_MODE")
    total=sum(w)
    exact=[extra*x/total for x in w]
    coarse=[int(math.floor(x)) for x in exact]
    remainder=extra-sum(coarse)
    order=sorted(range(n),key=lambda i:(-(exact[i]-coarse[i]),i))
    for i in order[:remainder]:coarse[i]+=1
    stakes=[100*(1+x) for x in coarse]
    if sum(stakes)!=p.budget or any(s<100 or s%100 for s in stakes):
        raise AssertionError("BET_BUDGET_NOT_CONSERVED")
    return stakes

def race_filter_passes(race:dict[str,Any],filt:str)->bool:
    if filt=="all":return True
    if filt.startswith("venue:"):return str(race.get("venue"))==filt.split(":",1)[1]
    no=int(race["raceNo"])
    n=len(race.get("horses",())) or int(race.get("fieldSize",0) or 0)
    surface=str(race.get("surface") or "").lower()
    distance=int(race.get("distanceM") or 0)
    if filt=="early_1_6":return no<=6
    if filt=="late_7_12":return no>=7
    if filt=="field_le10":return 0<n<=10
    if filt=="field_gt10":return n>10
    if filt=="turf":return surface in ("芝","turf")
    if filt=="dirt":return surface in ("ダート","dirt")
    if filt=="sprint_lt1600":return 0<distance<1600
    if filt=="middle_1600_2000":return 1600<=distance<=2000
    if filt=="stayer_gt2000":return distance>2000
    raise ValueError("UNKNOWN_PRE_RACE_REGIME_FILTER")

def one_race(race:dict[str,Any],candidates:list[dict[str,Any]],p:Policy):
    if not race_filter_passes(race,p.race_filter):return None
    picked=candidate_choices(candidates,p)
    if not picked:return None
    # The race bankroll is also a search dimension. Scaling uses ONLY the
    # fitted-model expected returns, never target JRA payouts or results.
    market_ev=sum(float(c["riskAdjustedE"]) for _,c in picked)/len(picked)
    factor=max(0.25,min(4.0,market_ev))
    if p.race_budget_mode=="flat":factor=1.
    elif p.race_budget_mode=="proportional_ev":pass
    elif p.race_budget_mode=="square_root_ev":factor=math.sqrt(factor)
    elif p.race_budget_mode=="stepwise_ev":factor=0.5 if market_ev<1 else (1 if market_ev<1.3 else 3)
    else:raise ValueError("UNRECOGNIZED_RACE_BUDGET_MODE")
    actual_budget=max(p.ticket_count*100,100*round(p.budget*factor/100))
    from dataclasses import replace
    sized=replace(p,budget=int(actual_budget))
    st=allocate_stakes(picked,sized)
    expected=sum(c["riskAdjustedE"]*s for (_,c),s in zip(picked,st))/actual_budget
    if expected<p.min_expected_ev:return None
    # PRE-RESULT DATA WALL: from this point all selection/ranking is frozen.
    ticket_results=[]
    for (_,c),stake in zip(picked,st):
        paid=int(c["payout100"])
        if paid<0:raise ValueError("NEGATIVE_ACTUAL_JRA_PAYOUT")
        ticket_results.append({
          "betType":str(c["key"][0]),"combination":"-".join(map(str,c["key"][1])),
          "stakeYen":stake,"returnYen":paid*(stake//100),
        })
    return {
      "raceId":str(race["raceId"]),"date":str(race["date"]),
      "venue":str(race["venue"]),"raceNo":int(race["raceNo"]),
      "estimatedEV":float(expected),"stake":actual_budget,
      "returned":sum(t["returnYen"] for t in ticket_results),
      "hit":int(any(t["returnYen"]>0 for t in ticket_results)),
      "tickets":ticket_results
    }

def select(groups:dict,scored:dict,p:Policy):
    """Visit every venue-day; skip only by predicted pre-result signals."""
    records=[]
    missed=Counter()
    for day,races in sorted(groups.items()):
        selected=[]
        for race in races:
            candidates=scored.get((day,race["raceId"]),[])
            if not candidates:
                missed["no_pre_result_candidates"]+=1
                continue
            prediction=one_race(race,candidates,p)
            if prediction is not None:selected.append(prediction)
        selected.sort(key=lambda r:(-r["estimatedEV"],r["raceNo"],r["raceId"]))
        if p.races_per_venue_day>0:
            selected=selected[:p.races_per_venue_day]
        if not selected:missed["no_selected_race_this_venue_day"]+=1
        records.extend(selected)
    return records,dict(missed)

def summarize(records:list[dict[str,Any]],eligible_venue_days:int|None=None)->dict[str,Any]:
    n=len(records)
    if not n:return {"races":0,"roiPct":0,"trimLargestTicketRoiPct":0,
                     "trimLargestRaceRoiPct":0,"hitRacePct":0,
                     "stakeYen":0,"returnYen":0,
                     "eligibleVenueDays":eligible_venue_days,
                     "promotionGatePassed":False}
    stake=0;returns=0;maximum_ticket=0;maximum_race=0;hits=0
    active=set();months=defaultdict(lambda:[0,0,0])
    for r in records:
        ts=r["tickets"]
        if not ts or len({(t["betType"],t["combination"]) for t in ts})!=len(ts):
            raise AssertionError("TICKET_DUPLICATE_OR_EMPTY")
        paid=sum(int(t["returnYen"]) for t in ts)
        invested=sum(int(t["stakeYen"]) for t in ts)
        if invested!=int(r["stake"]) or paid!=int(r["returned"]):
            raise AssertionError("NON_PAIRED_STAKE_AND_ACTUAL_JRA_RETURN")
        if invested<=0 or any(int(t["stakeYen"])<100 or int(t["stakeYen"])%100
                              for t in ts):raise AssertionError("JRA_STAKE_GRID_INVALID")
        stake+=invested;returns+=paid;maximum_race=max(maximum_race,paid)
        maximum_ticket=max(maximum_ticket,max(int(t["returnYen"]) for t in ts))
        hits+=int(paid>0)
        active.add((r["date"],r["venue"]))
        m=months[str(r["date"])[:7]]
        m[0]+=invested;m[1]+=paid;m[2]+=1
    assert maximum_ticket<=maximum_race<=returns
    hit_rate=100*hits/n
    roi=100*returns/stake
    trim_ticket=100*(returns-maximum_ticket)/stake
    trim_race=100*(returns-maximum_race)/stake
    month_rois={m:round(100*row[1]/row[0],4) for m,row in sorted(months.items())}
    minimum_month=min(month_rois.values())
    result={
      "races":n,"eligibleVenueDays":eligible_venue_days,
      "activeVenueDays":len(active),
      "venueDayCoveragePct":round(100*len(active)/eligible_venue_days,3) if eligible_venue_days else None,
      "stakeYen":stake,"returnYen":returns,"largestTicketReturnYen":maximum_ticket,
      "largestRaceReturnYen":maximum_race,
      "hitRaces":hits,"hitRacePct":round(hit_rate,4),
      "roiPct":round(roi,4),
      "trimLargestTicketRoiPct":round(trim_ticket,4),
      "trimLargestRaceRoiPct":round(trim_race,4),
      "minimumMonthRoiPct":minimum_month,
      "monthly":month_rois,
      "promotionGatePassed":False
    }
    return result

def robust_numeric_gate(m:dict[str,Any],minimum_races:int=300)->bool:
    """All 20/200/200 gates on the *identical actual JRA tickets and stake*."""
    n=int(m.get("races",0));stake=int(m.get("stakeYen",0));got=int(m.get("returnYen",0))
    top=int(m.get("largestTicketReturnYen",0));big=int(m.get("largestRaceReturnYen",0))
    if n<minimum_races or stake<100*n or not 0<=top<=big<=got:return False
    for key,value in (
        ("roiPct",100*got/stake),
        ("trimLargestTicketRoiPct",100*(got-top)/stake),
        ("trimLargestRaceRoiPct",100*(got-big)/stake)):
        if abs(float(m.get(key,0))-value)>.0001:return False
    return (float(m.get("hitRacePct",0))>=20
            and float(m["roiPct"])>=200
            and float(m["trimLargestTicketRoiPct"])>=200
            and float(m["trimLargestRaceRoiPct"])>=200
            and int(m.get("activeVenueDays",0))>=30)

def select_on_validation(validation:list[tuple[Policy,dict[str,Any]]],minimum_races:int=300):
    """A model policy is selected ONLY from earlier-year realized payoffs."""
    eligible=[(p,m) for p,m in validation if m["races"]>=minimum_races]
    if not eligible:return None
    return max(eligible,key=lambda z:(
        int(robust_numeric_gate(z[1],minimum_races)),
        float(z[1]["trimLargestRaceRoiPct"]),
        float(z[1]["trimLargestTicketRoiPct"]),
        float(z[1]["hitRacePct"])>=20,
        float(z[1]["venueDayCoveragePct"] or 0),
        -z[0].budget,
        repr(z[0])))

def self_test():
    assert len(all_policies(360,seed=20261108))==360
    assert all_policies(200,seed=20261108)==all_policies(200,seed=20261108)
    day=("2025-01-04","中山")
    groups={day:[{"raceId":str(j),"raceNo":j,"date":day[0],"venue":day[1]} for j in range(1,13)]}
    scored={}
    for race in groups[day]:
        scored[(day,race["raceId"])]=[
           {"key":(kind,(i+1,) if kind=="単勝" else (i+1,i+2)),
            "hitP":.03,"riskAdjustedE":2+i/10+int(kind=="ワイド")*.1,
            "payout100":(450 if int(race["raceNo"])%3==0 and i==0 else 0)}
           for i in range(7) for kind in ("単勝","ワイド")]
    p=Policy("expected",3,10,6,2000,"topheavy",0,0)
    records,miss=select(groups,scored,p)
    assert len(records)==12 and not miss
    assert all(len(r["tickets"])==6 and r["stake"]==2000 for r in records)
    assert all(len({(x["betType"],x["combination"]) for x in r["tickets"]})==6 for r in records)
    z=summarize(records,1)
    assert z["races"]==12 and z["activeVenueDays"]==1
    assert z["stakeYen"]==24000
    assert z["roiPct"]==round(100*z["returnYen"]/z["stakeYen"],4)
    p2=Policy("longshot",3,1,1,100,"equal",2,0)
    records2,_=select(groups,scored,p2)
    assert len(records2)==2 and all(x["stake"]==100 for x in records2)
    narrow=Policy("expected",3,10,2,500,"equal",0,0,"flat","late_7_12")
    late,_=select(groups,scored,narrow)
    assert len(late)==6 and all(row["raceNo"]>=7 for row in late)
    assert not race_filter_passes(groups[day][0],"venue:京都")
    assert race_filter_passes(groups[day][0],"venue:中山")
    # Vary stake per selected race by model value ONLY. All real stake remains
    # in ROI denominator, not just successful or larger-budget bets.
    dynamic=Policy("expected",3,10,6,2000,"equal",2,0,"proportional_ev")
    variable,_=select(groups,scored,dynamic)
    assert len(variable)==2 and all(x["stake"]>2000 for x in variable)
    assert all(sum(t["stakeYen"] for t in r["tickets"])==r["stake"] for r in variable)
    assert not robust_numeric_gate(summarize(records2,1))
    # Never drop the stake for the biggest win.
    huge=dict(z);huge.update({"races":500,"activeVenueDays":100,
        "stakeYen":1000000,"returnYen":4000000,
        "largestTicketReturnYen":1800000,"largestRaceReturnYen":1900000,
        "hitRacePct":30,"roiPct":400,
        "trimLargestTicketRoiPct":220,"trimLargestRaceRoiPct":210})
    assert robust_numeric_gate(huge)
    for x in ("roiPct","trimLargestTicketRoiPct","trimLargestRaceRoiPct"):
        broken=dict(huge);broken[x]=199.999
        assert not robust_numeric_gate(broken),x
    assert not robust_numeric_gate({**huge,"hitRacePct":19.999})
    assert not robust_numeric_gate({**huge,"returnYen":0})
    print("UNRESTRICTED_JRA_RACES_TICKETS_MARKETS_STAKES_AND_ROBUST_200_SELFTEST_OK")

if __name__=="__main__":
    if "--self-test" in sys.argv:self_test()
    else:raise SystemExit("Use the paired-2025-validation / frozen-2026-JRA runner; no in-sample standalone scoring")
